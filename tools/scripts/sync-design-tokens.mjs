#!/usr/bin/env node
// Converts libs/design-tokens/tokens.json (W3C DTCG, as exported from Penpot)
// into libs/design-tokens/src/theme.ts for React Native.
//
//   node tools/scripts/sync-design-tokens.mjs           # write theme.ts
//   node tools/scripts/sync-design-tokens.mjs --check   # exit 1 if theme.ts is stale
//
// Fails on token types it does not know, so new Penpot token kinds are noticed
// instead of silently dropped.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const inputPath = resolve(root, 'libs/design-tokens/tokens.json');
const outputPath = resolve(root, 'libs/design-tokens/src/theme.ts');
const REM_PX = 16;

const SUPPORTED = new Set(['color', 'dimension', 'fontFamily', 'fontWeight', 'number', 'duration']);

class TokenError extends Error {}

function isToken(node) {
  return node !== null && typeof node === 'object' && '$value' in node;
}

/** Flattens the DTCG tree into { 'color.text.primary': { type, value } }, inheriting $type from groups. */
function flatten(node, path = [], inheritedType) {
  const out = {};
  const groupType = node.$type ?? inheritedType;
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const childPath = [...path, key];
    if (isToken(child)) {
      out[childPath.join('.')] = { type: child.$type ?? groupType, value: child.$value };
    } else if (child && typeof child === 'object') {
      Object.assign(out, flatten(child, childPath, groupType));
    }
  }
  return out;
}

function resolveAlias(name, flat, seen = new Set()) {
  if (seen.has(name)) throw new TokenError(`Circular alias at "${name}"`);
  const token = flat[name];
  if (!token) throw new TokenError(`Unknown alias target "${name}"`);
  const match = typeof token.value === 'string' && token.value.match(/^\{(.+)\}$/);
  if (!match) return token;
  seen.add(name);
  const target = resolveAlias(match[1], flat, seen);
  return { type: token.type ?? target.type, value: target.value };
}

function convert(name, { type, value }) {
  if (!type)
    throw new TokenError(`Token "${name}" has no $type (set it on the token or a parent group)`);
  if (!SUPPORTED.has(type)) throw new TokenError(`Token "${name}" has unsupported $type "${type}"`);
  switch (type) {
    case 'color':
      if (typeof value === 'string') return value;
      if (value && typeof value.hex === 'string') return value.hex;
      throw new TokenError(`Color "${name}" must be a hex string or an object with "hex"`);
    case 'dimension': {
      const { value: n, unit } =
        typeof value === 'string'
          ? { value: parseFloat(value), unit: value.replace(/^[-\d.]+/, '') }
          : value;
      if (unit === 'px') return n;
      if (unit === 'rem') return n * REM_PX;
      throw new TokenError(`Dimension "${name}" has unsupported unit "${unit}"`);
    }
    case 'duration': {
      const { value: n, unit } =
        typeof value === 'string'
          ? { value: parseFloat(value), unit: value.replace(/^[-\d.]+/, '') }
          : value;
      return unit === 's' ? n * 1000 : n;
    }
    case 'fontFamily':
      return Array.isArray(value) ? value[0] : value;
    case 'fontWeight':
      return String(value);
    case 'number':
      return value;
  }
}

function setPath(target, path, value) {
  const keys = path.split('.');
  let node = target;
  for (const key of keys.slice(0, -1)) node = node[key] ??= {};
  node[keys.at(-1)] = value;
}

export function buildTheme(tokensJson) {
  const flat = flatten(tokensJson);
  const theme = {};
  for (const name of Object.keys(flat).sort()) {
    setPath(theme, name, convert(name, resolveAlias(name, flat)));
  }
  return theme;
}

function render(theme) {
  return `// GENERATED by tools/scripts/sync-design-tokens.mjs from tokens.json. Do not edit by hand.
// Run /sync-design-tokens (or node tools/scripts/sync-design-tokens.mjs) after updating tokens.json.

export const tokens = ${JSON.stringify(theme, null, 2)} as const;

export type Tokens = typeof tokens;
`;
}

function format(source) {
  const prettier = resolve(root, 'node_modules/.bin/prettier');
  return execFileSync(prettier, ['--stdin-filepath', outputPath], {
    input: source,
    encoding: 'utf8',
  });
}

function main() {
  const check = process.argv.includes('--check');
  let output;
  try {
    output = format(render(buildTheme(JSON.parse(readFileSync(inputPath, 'utf8')))));
  } catch (err) {
    if (err instanceof TokenError) {
      console.error(`sync-design-tokens: ${err.message}`);
      process.exit(1);
    }
    throw err;
  }
  if (check) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
    if (current !== output) {
      console.error('sync-design-tokens: src/theme.ts is out of date. Run /sync-design-tokens.');
      process.exit(1);
    }
    console.log('sync-design-tokens: theme.ts is up to date.');
    return;
  }
  writeFileSync(outputPath, output);
  console.log(`sync-design-tokens: wrote ${outputPath}`);
}

main();
